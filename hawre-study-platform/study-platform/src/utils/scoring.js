export function calculateScores(answers, extraTexts) {
    const s = [0, 0, 0, 0];
    const counts = [0, 0, 0, 0];
    questions.forEach(q => {
      const val = answers[q.id];
      if (!val && q.type !== "textarea" && q.type !== "textarea-big") return;
      if ((q.type === "textarea" || q.type === "textarea-big") && !val) {
        if (q.id === "q4" || q.id === "q13") {
          const sc = scoreForAnswer(q.id, val || "");
          s[q.section] += sc;
          counts[q.section] += 1;
        }
        return;
      }
      let sc = scoreForAnswer(q.id, val, extraTexts[q.id + "_extra"]);
      if (q.id === "q12" && extraTexts["q12_extra"]?.length > 5) {
        sc = Math.min(100, sc + 10);
      }
      s[q.section] += sc;
      counts[q.section] += 1;
    });
    return s.map((total, i) => (counts[i] ? Math.round(total / counts[i]) : 0));

}

